"""The paper's six development tables, built from this package's own CSVs.

Each function returns a complete `tabular` with the column specification, the header and
the body the paper's table of the same label already uses, every number wrapped in
`\\devnum{}`.  Nothing here writes into `paper/`: the files land in
`outputs/paper_tables/` and a person copies a row when they choose to.

The tables are the paper's, so the shapes are fixed here rather than derived: `tab:setup`
is a two-column description, `tab:rank` is the ranking scores, `tab:guard` the guard
family per load, `tab:adv` the corrupted rankings, `tab:k1` the single-server trace and
`tab:resid` the identity residuals.
"""

from __future__ import annotations

import re

from spjf_guard.experiment.report import devnum

RULE = r"\midrule"


def _thousands(value: float, digits: int = 0) -> str:
    """LaTeX thin-space thousands separators, as the paper prints large counts."""
    text = f"{value:,.{digits}f}"
    return text.replace(",", "{,}")


def _table(spec: str, header: str, body: list[str], label: str, caption: str) -> str:
    lines = [
        r"% Generated by scripts/emit_paper_tables.py; see GENERATED.md.  Do not hand edit.",
        r"\begin{table}[htbp]",
        r"\centering",
        r"\small",
        rf"\caption{{{caption}}}",
        rf"\label{{{label}}}",
        r"\setlength{\tabcolsep}{3pt}",
        rf"\begin{{tabular}}{{{spec}}}",
        r"\toprule",
        header + r" \\",
        RULE,
        *body,
        r"\bottomrule",
        r"\end{tabular}",
        r"\end{table}",
    ]
    return "\n".join(lines) + "\n"


def _cell(value, digits=2, interval=None) -> str:
    return devnum(value, digits, interval)


_PROMISE = re.compile(r"\((\d+(?:\.\d+)?)\)")


def policy_label(name: str) -> str:
    r"""`Guard(600)` prints as `Guard($\devnum{600}$)`: the promise in a name is a number
    the paper wraps like any other."""
    return _PROMISE.sub(lambda m: rf"($\devnum{{{float(m.group(1)):g}}}$)", name)


def _interval(row: dict, field: str) -> tuple | None:
    low, high = row.get(f"{field}_lo"), row.get(f"{field}_hi")
    if low is None or high is None or low == "" or high == "":
        return None
    return (float(low), float(high))


def _load_header(row: dict) -> str:
    return (
        rf"$\rho = \devnum{{{float(row['rho_target']):g}}}$, "
        rf"$k = \devnum{{{float(row['k']):g}}}$"
    )


def rank_table(table: list[dict], policies=("FCFS", "SJF", "SPJF-log", "SPJF-E")) -> str:
    """tab:rank -- the ranking scores at the three loads."""
    body: list[str] = []
    for level in sorted({int(r["level"]) for r in table}):
        block = [r for r in table if int(r["level"]) == level]
        body.append(_load_header(block[0]))
        for name in policies:
            row = next((r for r in block if r["policy"] == name), None)
            if row is None:
                continue
            body.append(
                f" & {name:<20s} & "
                + " & ".join(
                    [
                        _cell(float(row["p99_dl_s"]), 2),
                        _cell(float(row["gap_closed"]), 3, _interval(row, "gap_closed")),
                        _cell(float(row["reduction_pct"]), 1, _interval(row, "reduction_pct")),
                        _cell(float(row["mean_s"]), 3),
                    ]
                )
                + r" \\"
            )
        body.append(RULE)
    if body and body[-1] == RULE:
        body.pop()
    return _table(
        "llrlrr",
        r"Load & Policy & p99$_{\mathrm{dl}}$ & Gap closed & Red.\ (\%) & Mean",
        body,
        "tab:rank",
        "Ranking scores at the three load levels, five overlays.",
    )


def guard_table(table: list[dict], parameters: dict, guard_names) -> str:
    """tab:guard -- the guard family, its ablations and the comparators, per load."""
    body: list[str] = []
    for level in sorted({int(r["level"]) for r in table}):
        block = {r["policy"]: r for r in table if int(r["level"]) == level}
        first = next(iter(block.values()))
        head = _load_header(first)
        reference = block.get("FCFS")
        spjf = block.get("SPJF-E")
        if reference is not None and spjf is not None:
            base_p99 = f"{float(reference['p99_dl_s']):.2f}"
            spjf_p99 = f"{float(spjf['p99_dl_s']):.2f}"
            spjf_excess = _thousands(float(spjf["max_excess_s"]), 1)
            head += (
                rf"; FCFS p99$_{{\mathrm{{dl}}}}$ = \devnum{{{base_p99}}} s, "
                rf"SPJF-E \devnum{{{spjf_p99}}} s with max excess "
                rf"\devnum{{{spjf_excess}}} s"
            )
        body.append(rf"\multicolumn{{9}}{{l}}{{{head}}} \\")
        for name in guard_names:
            row = block.get(name)
            if row is None:
                continue
            params = parameters.get((level, name), {})
            label = policy_label(name)
            if params.get("skip_count"):
                label = rf"{label}, $\kappa={int(params['skip_count'])}$"
            body.append(
                f" & {label:<26s} & "
                + " & ".join(
                    [
                        _cell(params.get("promise_s", float("nan")), 0),
                        _cell(float(row["p99_dl_s"]), 2),
                        _cell(float(row["gap_closed"]), 3, _interval(row, "gap_closed")),
                        _cell(float(row["reduction_pct"]), 1),
                        _cell(float(row["max_excess_s"]), 1),
                        _cell(float(row["harm_s"]), 1),
                        _cell(float(row["fired_pct"]), 2),
                    ]
                )
                + r" \\"
            )
        body.append(RULE)
    if body and body[-1] == RULE:
        body.pop()
    return _table(
        "llrrlrrrr",
        r"Load & Policy & Promise & p99$_{\mathrm{dl}}$ & Gap closed & Red.\ (\%) & "
        r"Max exc. & Harm & Fired (\%)",
        body,
        "tab:guard",
        "The guard at three promises, its three budget shapes, and the comparators.",
    )


ADVERSARIAL_LABELS = {
    "reversed": "reversed",
    "random": "random",
    "top1short": "longest as shortest",
}


def adversarial_table(table: list[dict], promise: float = 600.0) -> str:
    """tab:adv -- each corrupted ranking alone and under the guard."""
    body: list[str] = []
    for level in sorted({int(r["level"]) for r in table}):
        block = {r["policy"]: r for r in table if int(r["level"]) == level}
        first = next(iter(block.values()))
        for i, (kind, label) in enumerate(ADVERSARIAL_LABELS.items()):
            bare, guarded = block.get(f"SPJF-{kind}"), block.get(f"Guard({promise:g})-{kind}")
            if bare is None or guarded is None:
                continue
            load = (
                rf"$\rho = \devnum{{{float(first['rho_target']):g}}}$" if i == 0 else " " * 21
            )
            body.append(
                f"{load} & {label:<20s} & "
                + " & ".join(
                    [
                        _cell(float(bare["p99_dl_s"]), 2),
                        _cell(float(guarded["p99_dl_s"]), 2),
                        _cell(float(bare["max_excess_s"]), 1),
                        _cell(float(guarded["max_excess_s"]), 1),
                        _cell(float(guarded["harm_s"]), 1),
                    ]
                )
                + r" \\"
            )
    return _table(
        "llrrrrr",
        r" & & \multicolumn{2}{c}{p99$_{\mathrm{dl}}$} & \multicolumn{2}{c}{Max excess} & "
        r"Harm \\"
        "\n"
        r"Load & Score & unguarded & guarded & unguarded & guarded & guarded",
        body,
        "tab:adv",
        "Corrupted rankings, alone and under the guard at the selected promise.",
    )


def single_server_table(table: list[dict], parameters: dict, policies) -> str:
    """tab:k1 -- the single-server trace, where the identity is exact."""
    body: list[str] = []
    for name in policies:
        row = next((r for r in table if r["policy"] == name), None)
        if row is None:
            continue
        params = parameters.get((0, name), {})
        label = policy_label(name)
        if params.get("skip_count"):
            label = rf"{label}, $\kappa={int(params['skip_count'])}$"
        promise = params.get("promise_s")
        body.append(
            f"{label:<28s} & "
            + " & ".join(
                [
                    _cell(promise, 0) if promise else "---",
                    _cell(float(row["p99_dl_s"]), 2),
                    _cell(float(row["gap_closed"]), 3, _interval(row, "gap_closed")),
                    _cell(float(row["max_excess_s"]), 1),
                    _cell(float(row["harm_s"]), 1),
                    _cell(float(row["fired_pct"]), 2),
                ]
            )
            + r" \\"
        )
    return _table(
        "lrrlrrr",
        r"Policy & Promise & p99$_{\mathrm{dl}}$ & Gap closed & Max exc. & Harm & Fired (\%)",
        body,
        "tab:k1",
        "The single-server configuration, where the identity of Theorem 1 is exact.",
    )


def residual_table(rows: list[dict], policies) -> str:
    """tab:resid -- how much of the excess the identity explains."""
    body: list[str] = []
    for level in sorted({int(r["level"]) for r in rows}):
        block = {r["policy"]: r for r in rows if int(r["level"]) == level}
        first = next(iter(block.values()))
        body.append(
            rf"$\rho = \devnum{{{float(first.get('rho_target', 0)):g}}}$, "
            rf"$k = \devnum{{{int(first['k'])}}}$"
        )
        for name in policies:
            row = block.get(name)
            if row is None:
                continue
            body.append(
                f" & {policy_label(name):<20s} & "
                + " & ".join(
                    [
                        _cell(float(row["max_abs_residual_L"]), 3),
                        _cell(float(row["ratio_to_bound"]), 3),
                        rf"\devnum{{{100.0 * float(row['share_residual_zero']):.1f}\%}}",
                        rf"\devnum{{{100.0 * float(row['samephase_share_sum_in']):.2f}\%}}",
                        _cell(float(row["r2_net_over_k"]), 3),
                        _cell(float(row["max_abs_error_s"]), 1),
                    ]
                )
                + r" \\"
            )
        body.append(RULE)
    if body and body[-1] == RULE:
        body.pop()
    return _table(
        "llrrrrrr",
        r"Load & Policy & $\max|D_i|/L$ & Ratio & $D_i = 0$ & Same-phase & $R^2$ "
        r"& worst err.\ (s)",
        body,
        "tab:resid",
        "Identity residuals on the first overlay: what $(In - Out)/k$ explains. "
        r"Same-phase is the share of $\sum In$ contributed by jobs dispatched in the "
        "same phase as the job they overtake, which cancels inside the proof.",
    )


def setup_table(items: list[tuple[str, str]]) -> str:
    """tab:setup -- the two-column description of the experiment."""
    body = [f"{name} & {value} \\\\" for name, value in items]
    return _table(
        r"p{0.24\textwidth}p{0.69\textwidth}",
        "Item & Value",
        body,
        "tab:setup",
        "What the development experiment runs, and what the selection chose.",
    )


def visibility_table(rows: list[dict], promise: float = 600.0) -> str:
    """Headline score variants under the unchanged selected guard parameters."""
    names = (
        ("original", f"Guard({promise:g})-original"),
        ("conservative", f"Guard({promise:g})"),
        ("static", f"Guard({promise:g})-static"),
    )
    body: list[str] = []
    for level in sorted({int(row["level"]) for row in rows}):
        block = {row["policy"]: row for row in rows if int(row["level"]) == level}
        first = next(iter(block.values()))
        body.append(rf"\multicolumn{{7}}{{l}}{{{_load_header(first)}}} \\")
        for label, policy in names:
            row = block.get(policy)
            if row is None:
                continue
            body.append(
                f" & {label:<14s} & "
                + " & ".join(
                    [
                        _cell(float(row["p99_dl_s"]), 2),
                        _cell(float(row["gap_closed"]), 3, _interval(row, "gap_closed")),
                        _cell(float(row["max_excess_s"]), 1),
                        _cell(float(row["harm_s"]), 1),
                        _cell(float(row["fired_pct"]), 2),
                    ]
                )
                + r" \\"
            )
        body.append(RULE)
    if body and body[-1] == RULE:
        body.pop()
    return _table(
        "llrlrrr",
        r"Load & Score history & p99$_{\mathrm{dl}}$ & Gap closed & Max exc. & Harm "
        r"& Fired (\%)",
        body,
        "tab:visibility",
        rf"Policy-consistent score variants at the unchanged selected Guard({promise:g}) "
        "parameters, over five overlays.",
    )


def visibility_audit_table(rows: list[dict]) -> str:
    """Original-clock exposure, averaged over the five primary overlays."""
    policies = ("FCFS", "SPJF-E", "Guard(300)", "Guard(600)", "Guard(1200)")
    body: list[str] = []
    for level in sorted({int(row["level"]) for row in rows}):
        for policy in policies:
            selected = [
                row for row in rows if int(row["level"]) == level and row["policy"] == policy
            ]
            if not selected:
                continue

            def mean(field: str) -> float:
                return sum(float(row[field]) for row in selected) / len(selected)

            body.append(
                f"{_cell(level, 0)} & {policy_label(policy):<22s} & "
                + " & ".join(
                    [
                        _cell(100.0 * mean("overall_affected_share"), 2),
                        _cell(100.0 * mean("deadline_affected_share"), 2),
                        _cell(mean("overall_premature_mean"), 1),
                        _cell(mean("overall_premature_p99"), 1),
                        _cell(100.0 * mean("unreplayed_overall_affected_share"), 2),
                    ]
                )
                + r" \\"
            )
        body.append(RULE)
    if body and body[-1] == RULE:
        body.pop()
    return _table(
        "llrrrrr",
        r"Level & Replay policy & Affected (\%) & Deadline (\%) & Mean records & "
        r"p99 records & Unreplayed (\%)",
        body,
        "tab:visibility_audit",
        "Exposure of original-clock outcome histories under replay. Counts are conditional "
        "on an affected job; unreplayed histories have no job in the same replay pool.",
    )


EXACT_POLICIES = ("SPJF-E", "Guard(300)", "Guard(600)", "Guard(1200)", "Aging(600)")


def exact_visibility_table(rows: list[dict]) -> str:
    """Original versus converged policy-specific scores under every frozen policy.

    Print the full predeclared family without choosing a policy from its outcomes.
    """
    body: list[str] = []
    for level in sorted({int(row["level"]) for row in rows}):
        block = [row for row in rows if int(row["level"]) == level]
        body.append(rf"\multicolumn{{8}}{{l}}{{{_load_header(block[0])}}} \\")
        keyed = {
            (row.get("base_policy") or row["policy"].split("|", 1)[0], row["variant"]): row
            for row in block
        }
        for policy in EXACT_POLICIES:
            for variant in ("original", "exact"):
                row = keyed.get((policy, variant))
                if row is None:
                    continue
                body.append(
                    f" & {policy_label(policy):<22s} & {variant:<9s} & "
                    + " & ".join(
                        [
                            _cell(float(row["p99_dl_s"]), 2),
                            _cell(float(row["gap_closed"]), 3, _interval(row, "gap_closed")),
                            _cell(float(row["max_excess_s"]), 1),
                            _cell(float(row["harm_s"]), 1),
                            _cell(float(row["fired_pct"]), 2),
                        ]
                    )
                    + r" \\"
                )
        body.append(RULE)
    if body and body[-1] == RULE:
        body.pop()
    return _table(
        "lllrlrrr",
        r"Load & Policy & Score visibility & p99$_{\mathrm{dl}}$ & Gap closed & "
        r"Max exc. & Harm & Fired (\%)",
        body,
        "tab:exact_visibility",
        "Original-clock and converged policy-specific scores under the frozen policies.",
    )


def same_copy_exposure_table(rows: list[dict]) -> str:
    """How often same-copy withholding changes a score and its dispatch-queue rank."""
    body: list[str] = []
    order = ("FCFS", *EXACT_POLICIES)
    for level in sorted({int(row["level"]) for row in rows}):
        block = {row["policy"]: row for row in rows if int(row["level"]) == level}
        for policy in order:
            row = block.get(policy)
            if row is None:
                continue
            body.append(
                f"{_cell(level, 0)} & {policy_label(policy):<22s} & "
                + " & ".join(
                    [
                        _cell(100.0 * float(row["affected_share"]), 2),
                        _cell(100.0 * float(row["deadline_affected_share"]), 2),
                        _cell(float(row["records_mean"]), 2),
                        _cell(float(row["records_p99"]), 1),
                        _cell(float(row["abs_delta_score_p99"]), 3),
                        _cell(float(row["abs_rank_displacement_p99"]), 1),
                        _cell(float(row["abs_rank_displacement_max"]), 0),
                    ]
                )
                + r" \\"
            )
        body.append(RULE)
    if body and body[-1] == RULE:
        body.pop()
    return _table(
        "llrrrrrrr",
        r"Level & Replay policy & Affected (\%) & Deadline (\%) & Records mean & "
        r"Records p99 & $|\Delta s|$ p99 & $|\Delta r|$ p99 & $|\Delta r|$ max",
        body,
        "tab:same_copy_exposure",
        "Same-copy outcome withholding and score-rank displacement. Statistics are averaged "
        "over overlays, except the maximum displacement, which is the largest over overlays.",
    )
